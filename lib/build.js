#!/usr/bin/env node
/* build.js :: concatenate lib/src/*.js (filename order) into the committed
 * lib/motion-kit.js and stamp a checksum. motion-kit.js is GENERATED; never
 * edit it by hand. Deterministic: sorts by filename, no timestamps in output.
 *
 *   node lib/build.js          # build
 *   node lib/build.js --check  # verify motion-kit.js matches src (CI guard)
 */
"use strict";
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const SRC = path.join(__dirname, "src");
const OUT = path.join(__dirname, "motion-kit.js");

function assemble() {
  const files = fs.readdirSync(SRC).filter(f => f.endsWith(".js")).sort();
  if (!files.length) throw new Error("no source files in lib/src");
  const body = files.map(f => fs.readFileSync(path.join(SRC, f), "utf8")).join("\n");
  const sum = crypto.createHash("sha256").update(body).digest("hex").slice(0, 16);
  const banner =
`/* motion-kit.js :: GENERATED by lib/build.js from lib/src/*.js. DO NOT EDIT.
 * sources: ${files.join(", ")}
 * src-sha256: ${sum}
 * Rebuild with: node lib/build.js
 */
`;
  return { text: banner + body + "\n", sum, files };
}

const { text, sum } = assemble();
const check = process.argv.includes("--check");

if (check) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (cur !== text) {
    console.error("motion-kit.js is STALE. Run: node lib/build.js");
    process.exit(1);
  }
  console.log("motion-kit.js up to date (src-sha256 " + sum + ")");
} else {
  fs.writeFileSync(OUT, text);
  console.log("built lib/motion-kit.js (src-sha256 " + sum + ")");
}
